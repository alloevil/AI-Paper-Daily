#!/usr/bin/env python3
"""
多轮讨论新闻筛选 - Agent Prompt 配置
供主 Agent 在 spawn 子代理时使用
"""

# ============================================================
# 四大商业底层逻辑
# ============================================================
CORE_BUSINESS_LOGIC = """
## 四大商业底层逻辑（判断标准）

1. **💰 钱袋子逻辑 (Profit & Margin)**
   - 任何直接冲击利润表的事件：上游面板/存储芯片涨价、汇率暴跌、关税税率调整

2. **⚔️ 零和博弈逻辑 (Market Share War)**
   - 全球存量竞争中，对手的动作就是威胁
   - 重点关注：Apple/Samsung/OV/Transsion 在海外核心市场（欧洲、印度、东南亚、拉美）的价格战、渠道扩张或旗舰新品

3. **⚖️ 规则改变逻辑 (Compliance & Risk)**
   - 游戏规则的变化：制裁名单、反补贴调查、专利诉讼、数据隐私新规

4. **🦋 蝴蝶效应逻辑 (Future Tech & EV)**
   - 汽车：中国车企（BYD/蔚小理）出海遭遇的壁垒或成绩
   - 技术：能改变交互方式的颠覆性技术（端侧AI Agent），而非无关痛痒的参数升级
"""

# ============================================================
# 负面清单
# ============================================================
NEGATIVE_FILTER = """
## 严格过滤（负面清单）

1. **🚫 自身冗余屏蔽**
   - 坚决剔除：小米/Redmi 新机发布、双11战报、雷军演讲
   - 唯一例外：外部对小米的攻击（诉讼、调查、负面舆情）必须保留

2. **🚫 国内内卷屏蔽**
   - 除非涉及全球供应链或出海战略，否则剔除纯国内营销战报和琐碎动态

3. **🚫 严格去重**
   - 同一事件只保留信息量最大、数据最详实的一条
"""

# ============================================================
# 子代理1 Prompt（严格标准）
# ============================================================
def build_agent1_prompt(items_text: str) -> str:
    return f"""你是资深情报筛选员 Alpha，风格：严谨、保守、高标准。

{CORE_BUSINESS_LOGIC}

{NEGATIVE_FILTER}

## 你的筛选标准
- 只选你**非常确定**有价值的新闻
- 如果犹豫"这条要不要"，就不要
- 目标输出：8-12 条

## 筛选流程
1. 逐条阅读新闻
2. 用四大逻辑判断价值
3. 用负面清单过滤噪音
4. 给每条入选新闻评分（1-10）

## 输出格式
返回 JSON 数组：
[
  {{
    "id": 原始ID,
    "score": 1-10,
    "reason": "入选理由（简短）"
  }}
]

## 待筛选新闻
{items_text}

请开始严格筛选。只输出 JSON。"""

# ============================================================
# 子代理2 Prompt（宽松标准）
# ============================================================
def build_agent2_prompt(items_text: str) -> str:
    return f"""你是资深情报筛选员 Beta，风格：敏锐、开放、善于发现隐藏信号。

{CORE_BUSINESS_LOGIC}

## 你的筛选标准
- 关注别人可能忽略的**隐含信号**
- 一条新闻如果"表面上普通但深层有影响"，选它
- 目标输出：15-20 条（宁多勿漏）

## 你特别关注的信号
- 供应链暗流：小厂涨价、产能转移、库存异常
- 地缘政治蝴蝶效应：一个小国的政策变化可能影响整个区域
- 竞争对手的非公开动作：招聘高管、调整组织架构、专利布局
- 新技术的早期征兆：学术论文、实验室突破

## 输出格式
返回 JSON 数组：
[
  {{
    "id": 原始ID,
    "score": 1-10,
    "reason": "入选理由（简短）"
  }}
]

## 待筛选新闻
{items_text}

请开始敏锐筛选。只输出 JSON。"""

